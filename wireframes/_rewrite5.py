def span(s):
    i, j = s.find('<div class="device"'), s.find('</div><!-- /.wf-main -->')
    return (i, j) if i >= 0 and j > i else (None, None)

check = '--check' in sys.argv
log, miss = [], []
for old, new, why in sorted(EDITS, key=lambda x: -len(x[0])):
    hit = 0
    for name in PAGES:
        p = W / name; s = p.read_text(encoding='utf-8')
        i, j = span(s)
        if i is None: continue
        b = s[i:j]
        if old not in b: continue
        hit += b.count(old)
        log.append({'file': name, 'old': old[:80], 'new': new[:80], 'why': why})
        if not check: p.write_text(s[:i] + b.replace(old, new) + s[j:], encoding='utf-8')
    if not hit and any(old in (W / n).read_text(encoding='utf-8') for n in PAGES):
        miss.append(old[:80])

if miss:
    print(f'НЕ ЗБІГЛОСЬ — {len(miss)}:')
    for u in miss: print('  ·', u)
else:
    print('усі правила знайшли ціль' + ('' if log else ' — усе вже застосовано'))
print(f'правок: {len(log)} у {len({x["file"] for x in log})} сторінках')
if not check and log:
    (W / '_rewrite5_log.json').write_text(json.dumps(log, ensure_ascii=False, indent=1), encoding='utf-8')
