def span(s):
    i, j = s.find('<div class="device"'), s.find('</div><!-- /.wf-main -->')
    return (i, j) if i >= 0 and j > i else (None, None)

check = '--check' in sys.argv
log, miss = [], []

for marker, why in DROPS:
    hit = 0
    for name in PAGES:
        p = W / name; s = p.read_text(encoding='utf-8')
        i, j = span(s)
        if i is None: continue
        b = s[i:j]; changed = False
        rx = re.compile(r'\s*<(p|li|dd|figcaption)\b[^>]*>(?:(?!</?\1\b).)*?</\1>', re.S)
        while True:
            for m in rx.finditer(b):
                if marker in re.sub(r'\s+', ' ', re.sub(r'<[^>]+>', '', m.group(0))):
                    b = b[:m.start()] + b[m.end():]; changed = True; hit += 1
                    log.append({'file': name, 'kind': 'drop', 'what': marker, 'why': why}); break
            else: break
        if changed and not check: p.write_text(s[:i] + b + s[j:], encoding='utf-8')
    if not hit and any(marker in (W / n).read_text(encoding='utf-8') for n in PAGES):
        miss.append('DROP ' + marker)

for old, new, why in sorted(T, key=lambda x: -len(x[0])):
    hit = 0
    for name in PAGES:
        p = W / name; s = p.read_text(encoding='utf-8')
        i, j = span(s)
        if i is None: continue
        b = s[i:j]
        if old not in b: continue
        hit += b.count(old)
        log.append({'file': name, 'kind': 'trim', 'what': old[:60], 'why': why})
        if not check: p.write_text(s[:i] + b.replace(old, new) + s[j:], encoding='utf-8')
    if not hit and any(old in (W / n).read_text(encoding='utf-8') for n in PAGES):
        miss.append('TRIM ' + old[:70])

if miss:
    print(f'НЕ ЗБІГЛОСЬ — {len(miss)}:')
    for u in miss: print('  ·', u)
else:
    print('усі правила знайшли ціль' + ('' if log else ' — усе вже застосовано'))
print(f'прибрано: {sum(1 for x in log if x["kind"]=="drop")} · скорочено: {sum(1 for x in log if x["kind"]=="trim")} '
      f'· сторінок: {len({x["file"] for x in log})}')
if not check and log:
    (W / '_rewrite7_log.json').write_text(json.dumps(log, ensure_ascii=False, indent=1), encoding='utf-8')
