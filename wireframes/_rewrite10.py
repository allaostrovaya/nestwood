# -*- coding: utf-8 -*-
"""Підсумок для передачі: прибрано документацію вайрфрейма й наш-голос.

Найгірше тут — абзац «Що станеться, якщо це не так…», який дослівно описує, що
цих станів «окремою сторінкою тут не намальовано» і що вони «гейт перед цим
екраном». Це нотатка для того, хто малює набір, а не текст застосунку.

    python3 wireframes/_rewrite10.py [--check]
"""
import pathlib, re, json, sys

W = pathlib.Path('wireframes')
F = 'share.html'

EDITS = [
 ('<h2 id="why">Навіщо ти тут</h2>', '<h2 id="why">Кому й навіщо</h2>', 'заголовок-питання до читача'),
 ('\n      <p>Цю форму відкривають із двох різних причин, і вони не одне й те саме.</p>', '',
  'пояснення, що екран має два сценарії'),
 ('<p>Перевірено 13 серпня 2026, 09:12 — той самий момент звірки, що на плані.</p>',
  '<p>Перевірено 13 серпня 2026, 09:12.</p>', 'самореференція на інший екран'),
 ('<p><b>Що станеться, якщо це не так:</b> якщо план ще чернетка — узгодженість не підтверджена, — '
  'підсумок не формується взагалі: замість нього повернення в план із поясненням, чого саме бракує. '
  'Якщо джерела не можна назвати поіменно, підсумок теж не йде назовні — це водночас провал довіри й, '
  'якщо в підсумку є дані Kartverket, порушення умов CC BY 4.0. Жодного з цих двох станів окремою '
  'сторінкою тут не намальовано — обидва є гейтом перед цим екраном, не його вмістом.</p>',
  '<p>Якщо план ще чернетка або джерела не названі, підсумок не формується: замість нього — '
  'повернення в план із поясненням, чого бракує.</p>',
  'документація вайрфрейма всередині макета'),
 ('<h2 id="trust">Для близьких: чому цьому плану можна довіряти</h2>',
  '<h2 id="trust">Для близьких</h2>', 'заголовок-аргумент'),
 ('<p>Переконує не наша впевненість, а те, що чотири джерела узгоджені й названі поіменно.</p>',
  '<p>Чотири джерела узгоджені й названі поіменно.</p>', 'ми-про-себе'),
 (' — офіційна шведсько-норвезька градація, показана як є, ніколи не перерахована нами',
  ' — офіційна шведсько-норвезька градація', 'ми-про-себе'),
 ('<h2 id="safety">Безпековий поділ: маршрут і час повернення</h2>',
  '<h2 id="safety">Маршрут і час повернення</h2>', 'вигаданий термін'),
 ('<p>Це те, що DNT рекомендує кожному самостійно: скажіть комусь, куди йдете і коли маєте повернутись.</p>',
  '<p>Скажи комусь, куди йдеш і коли маєш повернутись — це те, що радить DNT.</p>', 'звертання'),
]

check = '--check' in sys.argv
p = W / F; s = p.read_text(encoding='utf-8')
log, miss = [], []
for old, new, why in EDITS:
    if old not in s:
        if new not in s: miss.append(old[:70])
        continue
    s = s.replace(old, new, 1); log.append({'file': F, 'why': why})
if not check and log: p.write_text(s, encoding='utf-8')

if miss:
    print('НЕ ЗБІГЛОСЬ:'); [print('  ·', m) for m in miss]
else:
    print('усі правила знайшли ціль' + ('' if log else ' — усе вже застосовано'))
print(f'правок: {len(log)}')
if not check and log:
    (W / '_rewrite10_log.json').write_text(json.dumps(log, ensure_ascii=False, indent=1), encoding='utf-8')
