def span(s):
    i, j = s.find('<div class="device"'), s.find('</div><!-- /.wf-main -->')
    return (i, j) if i >= 0 and j > i else (None, None)

check = '--check' in sys.argv
log, miss = [], []

def edit(name, fn):
    p = W / name
    s = p.read_text(encoding='utf-8')
    i, j = span(s)
    if i is None: return None
    body = s[i:j]
    new = fn(body)
    if new is None or new == body: return False
    if not check: p.write_text(s[:i] + new + s[j:], encoding='utf-8')
    return True

# 1. видалення елементів
for name, tag, marker, why in DROPS:
    def drop(body, tag=tag, marker=marker):
        rx = re.compile(rf'\s*<{tag}\b[^>]*>(?:(?!</?{tag}\b).)*?</{tag}>', re.S)
        for m in rx.finditer(body):
            if marker in re.sub(r'<[^>]+>', '', m.group(0)):
                return body[:m.start()] + body[m.end():]
        return None
    ok = edit(name, drop)
    if ok: log.append({'file': name, 'kind': 'drop', 'old': marker, 'new': '—', 'why': why})
    elif marker in (W / name).read_text(encoding='utf-8'): miss.append(marker)

# 2. дослівні заміни — довші першими
for old, new in sorted(T, key=lambda x: -len(x[0])):
    hit = 0
    for name in PAGES:
        if edit(name, lambda b, o=old, n=new: b.replace(o, n) if o in b else None):
            hit += 1
            log.append({'file': name, 'kind': 'text', 'old': old, 'new': new or '—', 'why': 'рев\'ю-текст'})
    if not hit and any(old in (W / n).read_text(encoding='utf-8') for n in PAGES):
        miss.append(old)

# 3. позначки мок-даних
for old, (short, tip) in MOCK.items():
    hit = 0
    def swap(body, o=old, s_=short, t=tip):
        rx = re.compile(r'<small\b[^>]*data-mock[^>]*>(.*?)</small>', re.S)
        out, last, done = [], 0, False
        for m in rx.finditer(body):
            if re.sub(r'\s+', ' ', re.sub(r'<[^>]+>', '', m.group(1))).strip() != o: continue
            attr = f' title="{t}"' if t else ''
            out.append(body[last:m.start()]); out.append(f'<small data-mock{attr}>{s_}</small>')
            last = m.end(); done = True
        if not done: return None
        out.append(body[last:]); return ''.join(out)
    for name in PAGES:
        if edit(name, swap):
            hit += 1
            log.append({'file': name, 'kind': 'mock', 'old': old, 'new': short, 'why': 'комерційна причина — у tooltip'})
    if not hit and not any(f'>{short}</small>' in (W / n).read_text(encoding='utf-8') for n in PAGES):
        miss.append(old)

