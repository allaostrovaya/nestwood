def device_span(s):
    i = s.find('<div class="device"')
    j = s.find('</div><!-- /.wf-main -->')
    return (i, j) if i >= 0 and j > i else (None, None)

check = '--check' in sys.argv
log, unmatched = [], []
for old, new, why in EDITS:
    hits = 0
    for name in SCOPE:
        p = W / name
        s = p.read_text(encoding='utf-8')
        i, j = device_span(s)
        if i is None: continue
        body = s[i:j]
        n = body.count(old)
        if not n: continue
        hits += n
        log.append({'file': name, 'old': old, 'new': new, 'why': why, 'n': n})
        if not check:
            p.write_text(s[:i] + body.replace(old, new) + s[j:], encoding='utf-8')
    if not hits: unmatched.append(old)

if unmatched:
    print(f'НЕ ЗБІГЛОСЬ — {len(unmatched)}:')
    for u in unmatched: print('  ·', u[:95])
else:
    print('усі заміни знайшли ціль')

if not check:
    (W / '_rewrite_log.json').write_text(json.dumps(log, ensure_ascii=False, indent=1), encoding='utf-8')
    print(f'застосовано: {sum(x["n"] for x in log)} замін у '
          f'{len({x["file"] for x in log})} сторінках · правил {len({x["old"] for x in log})}')
