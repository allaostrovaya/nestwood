def span(s):
    i, j = s.find('<div class="device"'), s.find('</div><!-- /.wf-main -->')
    return (i, j) if i >= 0 and j > i else (None, None)

check = '--check' in sys.argv
log, miss = [], []
for grp, rules in (('A', A), ('B', B), ('C', C), ('F', F)):
    for old, new in rules:
        hit = 0
        for name in PAGES:
            p = W / name; s = p.read_text(encoding='utf-8')
            i, j = span(s)
            if i is None: continue
            b = s[i:j]
            if old not in b: continue
            hit += b.count(old); log.append({'group': grp, 'file': name, 'old': old[:60], 'new': new[:60]})
            if not check: p.write_text(s[:i] + b.replace(old, new) + s[j:], encoding='utf-8')
        if not hit:
            plain = re.sub(r'\s+', ' ', re.sub(r'<[^>]+>', '', old)).strip()
            still = plain and any(plain in re.sub(r'\s+', ' ', re.sub(r'<[^>]+>', '', (W / n).read_text(encoding='utf-8')))
                                  for n in PAGES)
            if still: miss.append(f'{grp} {old[:70]}')

if miss:
    print(f'НЕ ЗБІГЛОСЬ — {len(miss)}:')
    for m in miss: print('  ·', m)
else:
    print('усі правила знайшли ціль' + ('' if log else ' — усе вже застосовано'))
import collections
c = collections.Counter(x['group'] for x in log)
print(f'правок: {len(log)} · ' + ' · '.join(f'{k}:{v}' for k, v in sorted(c.items()))
      + f' · сторінок: {len({x["file"] for x in log})}')
if not check and log:
    (W / '_rewrite14_log.json').write_text(json.dumps(log, ensure_ascii=False, indent=1), encoding='utf-8')
